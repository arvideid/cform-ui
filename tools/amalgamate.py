#!/usr/bin/env python3
"""Pack the layout headers into one file an external project can drop in.

cf_layout's whole public surface is types.h, base.h, style.h and layout.h. The
generated header replaces the include directory: a consumer drops cf_layout.h
beside its own source, links the cf_layout objects and configures no search
path. Take it instead of the directory, not beside it — the merged body carries
the guards of the headers it holds, so a second copy of one of them arrives as
duplicate declarations.

Intra-project includes are dropped because the packed set already holds what
they name. One outside that set has no answer here, so the script fails and
names it rather than shipping a header that does not compile.
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
INCLUDE = ROOT / "include" / "cf"
PACKED = ("types.h", "base.h", "style.h", "layout.h")
GUARD = "CF_LAYOUT_H"

PROJECT_INCLUDE = re.compile(r'^\s*#\s*include\s+"cf/([a-z0-9_/]+\.h)"')
SYSTEM_INCLUDE = re.compile(r"^\s*#\s*include\s+<([a-zA-Z0-9_./-]+)>")


def fail(message):
    print(f"amalgamate: {message}", file=sys.stderr)
    sys.exit(1)


def strip_guard(lines, name):
    if not lines or not lines[0].startswith("#ifndef") or not lines[1].startswith("#define"):
        fail(f"include/cf/{name} does not open with a guard pair")
    if not lines[-1].lstrip().startswith("#endif"):
        fail(f"include/cf/{name} does not close its guard with an #endif")

    return lines[2:-1]


def read_body(name, system_includes):
    lines = strip_guard((INCLUDE / name).read_text(encoding="utf-8").splitlines(), name)
    body = []

    for line in lines:
        project = PROJECT_INCLUDE.match(line)
        if project:
            if project.group(1) not in PACKED:
                fail(
                    f"include/cf/{name} reaches cf/{project.group(1)}, "
                    "which is outside the packed set")
            continue

        system = SYSTEM_INCLUDE.match(line)
        if system:
            header = f"<{system.group(1)}>"
            if header not in system_includes:
                system_includes.append(header)
            continue

        body.append(line)

    return "\n".join(body).strip("\n")


def pack():
    system_includes = []
    bodies = [read_body(name, system_includes) for name in PACKED]
    source_set = ", ".join(f"include/cf/{name}" for name in PACKED)

    parts = [
        "/* Generated by tools/amalgamate.py — do not edit.",
        f" * Packed from {source_set},",
        " * in that order. */",
        f"#ifndef {GUARD}",
        f"#define {GUARD}",
        "",
        "\n".join(f"#include {header}" for header in system_includes),
        "",
        "\n\n".join(bodies),
        "",
        f"#endif /* {GUARD} */",
    ]

    return "\n".join(parts) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Write the amalgamated cf_layout.h.")
    parser.add_argument("--out", type=pathlib.Path, help="write here instead of standard output")
    args = parser.parse_args()

    text = pack()
    if args.out:
        args.out.write_text(text, encoding="utf-8", newline="\n")
    else:
        sys.stdout.write(text)

    return 0


if __name__ == "__main__":
    sys.exit(main())
